#!/usr/bin/env python3
"""Harness selection regressions: install.sh has no default harness and each adapter
deploys only its own destinations. Runs against the real repo with an isolated HOME;
no network, no model calls, nothing written outside the temp HOME and build/."""
import os
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def run(args, home, check=True):
    env = dict(os.environ, HOME=str(home), PI_CODING_AGENT_DIR=str(home / '.omp/agent'),
               TMPDIR=str(home / '.tmp'))
    (home / '.tmp').mkdir(exist_ok=True)
    return subprocess.run(args, cwd=ROOT, env=env, text=True, capture_output=True, check=check)


def entries(home):
    return sorted(p.name for p in home.iterdir() if p.name != '.tmp')


class HarnessDispatchTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        subprocess.run([str(ROOT / 'bin/aimain'), 'build'], cwd=ROOT, check=True, capture_output=True)

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.home = Path(self.tmp.name)

    def test_no_harness_builds_only(self):
        result = run([str(ROOT / 'install.sh')], self.home)
        self.assertIn('No harness selected', result.stdout)
        self.assertEqual(entries(self.home), [])

    def test_unknown_harness_is_rejected(self):
        result = run([str(ROOT / 'install.sh'), '--harness', 'bogus'], self.home, check=False)
        self.assertEqual(result.returncode, 2)
        self.assertEqual(entries(self.home), [])

    def test_codex_alone_touches_only_codex_home(self):
        run([str(ROOT / 'install.sh'), '--harness', 'codex'], self.home)
        self.assertEqual(entries(self.home), ['.codex'])
        entry = (self.home / '.codex/AGENTS.md').read_text()
        self.assertTrue(entry.startswith('<!-- generated by ai-main'))
        run([str(ROOT / 'adapters/codex/deploy.sh'), '--quiet'], self.home)  # idempotent

    def test_codex_alias_matches_explicit_selection(self):
        # Orca/OMP (retired 2026-10): see archive/2026-10-orca-omp/adapters/omp
        run([str(ROOT / 'install.sh'), '--harness', 'codex', '--quiet'], self.home)
        first = entries(self.home)
        self.assertEqual(first, ['.codex'])
        other = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, other, True)
        run([str(ROOT / 'install.sh'), '--codex', '--quiet'], other)
        self.assertEqual(entries(other), first)
        rel = '.codex/AGENTS.md'
        self.assertEqual((self.home / rel).read_text(), (other / rel).read_text())


if __name__ == '__main__':
    unittest.main(verbosity=2)
