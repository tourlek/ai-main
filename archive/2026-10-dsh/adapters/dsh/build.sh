#!/usr/bin/env bash
# Build DSH outputs under build/dsh/ (called by `aimain build`; writes nothing outside the repo).
#   AGENTS.md         -> ~/.dsh/AGENTS.md   (slim, from adapters/dsh/AGENTS.md)
#   agents-AGENTS.md  -> ~/.agents/AGENTS.md (shared profile incl. RULES, manual RTK prefix)
set -euo pipefail
AI_MAIN="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
OUT="${AI_MAIN}/build/dsh"
MARKER="<!-- generated by ai-main — edit ai-main/config/ + memory/ instead -->"
[ -f "${AI_MAIN}/build/full/SYSTEM.md" ] || { echo "adapters/dsh/build.sh: run aimain build first" >&2; exit 1; }
mkdir -p "$OUT"
cp "${AI_MAIN}/adapters/dsh/AGENTS.md" "${OUT}/AGENTS.md"
{
    echo "$MARKER"
    echo
    cat "${AI_MAIN}/config/RTK.manual.md"
    echo
    cat "${AI_MAIN}/build/full/SYSTEM.md"
} > "${OUT}/agents-AGENTS.md"
echo "  ✓ build/dsh: AGENTS.md ($(wc -c < "${OUT}/AGENTS.md" | tr -d ' ') B), agents-AGENTS.md ($(wc -c < "${OUT}/agents-AGENTS.md" | tr -d ' ') B)"
